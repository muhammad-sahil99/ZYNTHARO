def _render(value: Any, params: dict[str, Any]) -> Any:
    """Substitute {placeholders} in a step argument with call-time parameters."""
    if isinstance(value, str):
        try:
            return value.format(**params)
        except (KeyError, IndexError, ValueError):
            return value
    if isinstance(value, list):
        return [_render(item, params) for item in value]
    if isinstance(value, dict):
        return {key: _render(item, params) for key, item in value.items()}
    return value


def run_steps(ctx: ActionContext, step_name: str, params: dict[str, Any], continue_on_error: bool = False) -> dict[str, Any]:
    """Execute a recorded sequence through the action registry (so it stays capability-gated)."""
    steps = STEPS.get(step_name)
    if not steps:
        raise ActionFailed(f"unknown step sequence: {step_name}")
    results: list[dict[str, Any]] = []
    started = time.time()
    for index, step in enumerate(steps):
        action_name = step.get("action", "")
        args = _render(step.get("args", {}), params)
        # The registry enforces the caller's capabilities: a plugin cannot escalate.
        verify = step.get("verify_capability")
        if verify and verify not in ctx.capabilities:
            raise ActionFailed(f"step {index} ({action_name}) requires capability {verify}")
        registry = getattr(ctx, "registry", None)
        if registry is None:
            raise ActionFailed("plugin needs a registry on the ActionContext")
        result = registry.invoke(action_name, ctx, **args)
        entry = {"step": index, "action": action_name, "ok": result.ok, "detail": str(result.output or result.error)[:500]}
        results.append(entry)
        if not result.ok and not continue_on_error:
            raise ActionFailed(f"step {index} failed: {action_name}: {result.error}", {"results": results})
    return {"steps_run": len(results), "results": results, "seconds": round(time.time() - started, 3)}


def self_test(registry: Any) -> dict[str, Any]:
    """Run before installation: the plugin proves it works or it is not installed."""
    checked: list[str] = []
    for name in ACTIONS:
        if name not in globals():
            return {"ok": False, "error": f"declared action {name} is missing from the module"}
        checked.append(name)
    missing: list[str] = []
    for step_name, steps in STEPS.items():
        for step in steps:
            target = step.get("action", "")
            if target and registry.get(target) is None:
                missing.append(f"{step_name} -> {target}")
    if missing:
        return {"ok": False, "error": f"steps reference unknown actions: {missing[:8]}"}
    return {"ok": True, "actions": checked, "sequences": sorted(STEPS), "checked_actions": len(registry)}
