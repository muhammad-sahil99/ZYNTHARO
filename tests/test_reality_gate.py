"""Reality Gate tests: the scanner must catch fake functionality and stay quiet about harnesses.

Each test writes a small throwaway repository with a real file layout (``zyntharo/`` for shipped
code, ``tests/`` for the harness) rather than mocking the scanner, because the property under
test is precisely "what does this rule do to this source text".
"""

from __future__ import annotations

import json
import os
import tempfile
import textwrap
import unittest
from pathlib import Path

from tools.reality_gate import BLOCKING, REVIEW, scan_repository

BAD_MODULE = '''
"""A module with banned patterns."""
from unittest import mock

import time


def apply_settings(path):
    return True


def do_nothing():
    pass


def promised_but_missing():
    raise NotImplementedError


class MockBrowser:
    def click(self, target):
        return {"ok": True}


def wait_a_bit():
    time.sleep(2)          # TODO: replace with a real condition
    try:
        return mock.call()
    except Exception:
        pass


def advertise():
    return "demo mode is on"
'''


class ScannerTestCase(unittest.TestCase):
    def setUp(self):
        self.root = Path(tempfile.mkdtemp(prefix="reality-"))
        (self.root / "zyntharo").mkdir()
        (self.root / "tests").mkdir()

    def write(self, relative: str, source: str) -> Path:
        path = self.root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(textwrap.dedent(source), encoding="utf-8")
        return path

    def scan(self, allowlist: list[dict] | None = None) -> dict:
        path = self.root / "allow.json"
        path.write_text(json.dumps({"allow": allowlist or []}), encoding="utf-8")
        return scan_repository(self.root, allowlist_path=path)


class BlockingRuleTests(ScannerTestCase):
    def test_fakes_and_finished_work_are_blocked_in_shipped_code(self):
        self.write("zyntharo/dodgy.py", BAD_MODULE)
        report = self.scan()
        rules = {finding["rule"] for finding in report["blocking"]}
        self.assertEqual(
            rules,
            {
                "test_double_import",
                "fake_identifier",
                "hardcoded_success",
                "empty_body",
                "not_implemented",
                "unfinished_work",
                "fake_mode_string",
            },
        )
        self.assertFalse(report["clean"])

    def test_the_harness_is_counted_separately_and_never_blocks(self):
        self.write("tests/test_dodgy.py", BAD_MODULE)
        report = self.scan()
        self.assertEqual(report["blocking"], [])
        self.assertTrue(report["clean"])
        self.assertGreater(report["harness_hits"], 0)

    def test_an_identifier_that_merely_contains_a_fragment_is_not_flagged(self):
        """``placeholders`` is a real variable name, not a fake; word matching matters."""
        self.write(
            "zyntharo/sql.py",
            '''
def build(count):
    placeholders = ", ".join("?" for _ in range(count))
    return placeholders


class Placeholders:
    """A name built from the word, so it must not be mistaken for a double."""
''',
        )
        report = self.scan()
        self.assertEqual(report["blocking"], [])


class ReviewRuleTests(ScannerTestCase):
    def test_legitimate_patterns_are_listed_not_banned(self):
        self.write(
            "zyntharo/interfaces.py",
            '''
import time


class Transport:
    """An interface: raising here is the declaration, not a fake implementation."""

    def send(self, payload):
        raise NotImplementedError


def poll(reader):
    for _ in range(5):
        if reader():
            return True
        time.sleep(0.2)
    return False


def best_effort():
    try:
        return 1
    except Exception:
        pass
''',
        )
        report = self.scan()
        self.assertEqual(report["blocking"], [])
        rules = {finding["rule"] for finding in report["review"]}
        self.assertIn("interface_declaration", rules)
        self.assertIn("sleep_wait", rules)
        self.assertIn("swallowed_error", rules)
        self.assertEqual(report["by_rule"].get("empty_body"), None)


class WaiverTests(ScannerTestCase):
    def test_a_waiver_is_recorded_with_its_reason_rather_than_hiding_the_rule(self):
        path = self.write("zyntharo/generated.py", "def stub_thing():\n    return True\n")
        report = self.scan(
            [
                {
                    "rule": "fake_identifier",
                    "path": "zyntharo/generated.py",
                    "line": 1,
                    "reason": "generated by the SDK and reviewed by hand on 2026-10-27",
                }
            ]
        )
        self.assertEqual([f["rule"] for f in report["blocking"]], [])
        self.assertEqual(report["allowed_hits"], 1)
        self.assertIn("reviewed by hand", report["allowed"][0]["detail"])
        self.assertTrue(str(path).endswith("generated.py"))


class RealRepositoryTests(unittest.TestCase):
    def test_the_shipped_package_has_no_banned_patterns(self):
        from tools.reality_gate import ROOT

        report = scan_repository(ROOT)
        self.assertEqual(report["blocking"], [], f"banned patterns found: {report['blocking'][:3]}")
        self.assertGreater(report["files_scanned"], 30)
        self.assertTrue(report["clean"])

    def test_every_finding_carries_a_rule_and_a_location(self):
        from tools.reality_gate import ROOT

        report = scan_repository(ROOT)
        for finding in report["review"]:
            self.assertTrue(finding["rule"])
            self.assertTrue(finding["path"])
            self.assertGreater(finding["line"], 0)
            self.assertIn(finding["severity"], (BLOCKING, REVIEW))


if __name__ == "__main__":
    unittest.main()
